package demo1_abstract_class;

/**
 * 题目：图形信息与面积计算
 *
 * 一家图形服务公司要开发一个“图形信息展示”功能。当前系统需要处理两种图形：矩形和圆形。
 * 后续还可能增加其他图形，因此主程序不能针对每一种具体图形分别编写处理代码。
 *
 * 请完成以下业务需求：
 *
 * 1. 创建名为 Shape 的抽象类，作为所有图形的共同父类。Shape 中使用 area 保存面积，
 *    并定义 draw、calcArea 和 getArea，分别表示展示图形信息、计算面积和获取面积。
 *
 * 2. 创建名为 Rect 的矩形类：
 *    - 保存矩形的 length 和 width；
 *    - 矩形信息必须包含“矩形”、长度和宽度；
 *    - 矩形面积按照“长度 × 宽度”计算。
 *
 * 3. 创建名为 Circle 的圆形类：
 *    - 保存圆形的 r；
 *    - 使用名为 PI 的常量表示圆周率，值为 3.14；
 *    - 圆形信息必须包含“圆形”和半径；
 *    - 圆形面积按照“3.14 × 半径 × 半径”计算。
 *
 * 4. 在 Main 中准备以下两条业务数据，顺序不能改变：
 *    - 一个 length 为 6、width 为 4 的矩形；
 *    - 一个 r 为 3 的圆形。
 *    使用名为 shapes 的统一图形集合保存这两条数据。
 *
 * 5. 通过统一的图形引用处理 shapes 中的所有图形。主程序不能通过判断具体图形类型来分别
 *    编写矩形处理流程和圆形处理流程。
 *
 * 6. 程序运行结果必须能够看出：
 *    - 第一个图形是长 6、宽 4 的矩形，面积为 24.0；
 *    - 第二个图形是半径 3 的圆形，面积为 28.26。
 *
 * 7. 输出文字可以自行组织，但必须同时展示图形类型、图形数据和计算结果，且矩形结果在前、
 *    圆形结果在后。
 *
 * 代码要求：
 * - 本题必须体现抽象类、抽象方法、继承、方法重写和多态。
 * - 不能直接创建 Shape 对象。
 * - 除 Main.java 外，Shape、Rect、Circle 等独立类分别放在独立的 Java 文件中。
 */
public class Main {
    public static void main(String[] args) {
        Shape[] shapes = {
                new Rect(6, 4),
                new Circle(3)
        };

        for (Shape shape : shapes) {
            shape.draw();
            shape.calcArea();
            System.out.printf("面积 = %.2f%n", shape.getArea());
        }
    }
}
